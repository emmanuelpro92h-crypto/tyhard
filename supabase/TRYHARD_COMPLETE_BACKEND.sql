create or replace function public.remote_content_safe_slug(p_value text, p_fallback text default 'file')
returns text
language plpgsql
immutable
as $$
declare
    v_slug text;
begin
    v_slug := lower(regexp_replace(trim(coalesce(p_value, '')), '[^a-zA-Z0-9._-]+', '-', 'g'));
    v_slug := trim(both '-' from v_slug);
    v_slug := trim(both '.' from v_slug);

    if v_slug = '' then
        v_slug := lower(regexp_replace(trim(coalesce(p_fallback, 'file')), '[^a-zA-Z0-9._-]+', '-', 'g'));
        v_slug := trim(both '-' from v_slug);
        v_slug := trim(both '.' from v_slug);
    end if;

    if v_slug = '' then
        v_slug := 'file';
    end if;

    return left(v_slug, 80);
end;
$$;

create or replace function public.remote_content_safe_path(
    p_value text,
    p_category text default 'files',
    p_file_name text default 'content.bin'
)
returns text
language plpgsql
immutable
as $$
declare
    v_path text;
begin
    v_path := trim(coalesce(p_value, ''));
    v_path := replace(v_path, E'\\', '/');
    v_path := regexp_replace(v_path, '[^a-zA-Z0-9._/~+-]+', '-', 'g');
    v_path := regexp_replace(v_path, '/+', '/', 'g');
    v_path := trim(both '/' from v_path);

    if v_path = '' then
        v_path := public.remote_content_safe_slug(coalesce(p_category, 'files'), 'files')
            || '/'
            || public.remote_content_safe_slug(coalesce(p_file_name, 'content.bin'), 'content.bin');
    end if;

    if v_path = '' or v_path ~ '(^|/)\.\.(/|$)' then
        raise exception 'Invalid target path';
    end if;

    if v_path !~ '/' or v_path !~ '\.[a-zA-Z0-9~+-]+$' then
        raise exception 'Target path must include a folder and file name';
    end if;

    return left(v_path, 180);
end;
$$;

