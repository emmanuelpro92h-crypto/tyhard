create or replace function public.admin_publish_remote_content()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_next_version integer;
    v_published_at timestamptz := now();
    v_files jsonb;
    v_manifest jsonb;
begin
    if not public.is_license_admin() then
        raise exception 'Not authorized';
    end if;

    select coalesce(max(version), 0) + 1
    into v_next_version
    from public.remote_content_releases;

    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'id', f.id::text,
                'slug', f.slug,
                'name', f.name,
                'description', f.description,
                'category', f.category,
                'target_bundle', f.target_bundle,
                'target_path', f.target_path,
                'version', f.version,
                'storage_path', f.storage_path,
                'file_name', f.file_name,
                'mime_type', f.mime_type,
                'byte_size', f.byte_size,
                'sha256', lower(f.sha256),
                'is_active', f.is_active,
                'deleted_at', f.deleted_at,
                'published_at', v_published_at
            )
            order by f.category, f.name, f.id
        ),
        '[]'::jsonb
    )
    into v_files
    from public.remote_content_files f;

    v_manifest := jsonb_build_object(
        'success', true,
        'message', 'Manifest ready',
        'version', v_next_version,
        'published_at', v_published_at,
        'files', v_files
    );

    insert into public.remote_content_releases (
        version,
        manifest,
        published_by,
        published_at
    )
    values (
        v_next_version,
        v_manifest,
        auth.uid(),
        v_published_at
    );

    update public.remote_content_files f
    set published_at = v_published_at
    where f.published_at is null
       or f.updated_at >= f.published_at
       or f.deleted_at is not null;

    return v_manifest;
end;
$$;

create or replace function public.get_remote_content_manifest(
    p_license_key text,
    p_device_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_license jsonb;
    v_manifest jsonb;
begin
    v_license := public.check_license(p_license_key, p_device_id)::jsonb;

    if coalesce((v_license->>'success')::boolean, false) = false then
        return jsonb_build_object(
            'success', false,
            'message', coalesce(v_license->>'message', 'License check failed'),
            'version', 0,
            'published_at', null,
            'files', jsonb_build_array()
        );
    end if;

    select r.manifest
    into v_manifest
    from public.remote_content_releases r
    order by r.version desc
    limit 1;

    if v_manifest is null then
        return jsonb_build_object(
            'success', true,
            'message', 'No published content yet',
            'version', 0,
            'published_at', null,
            'files', jsonb_build_array()
        );
    end if;

    return v_manifest;
end;
$$;

