create or replace function public.normalize_license_key(p_license_key text)
returns text
language sql
immutable
as $$
    select upper(regexp_replace(trim(coalesce(p_license_key, '')), '\s+', '', 'g'));
$$;

create or replace function public.generate_secure_license_key(p_prefix text default 'TRYHARD')
returns text
language plpgsql
as $$
declare
    v_prefix text := upper(regexp_replace(trim(coalesce(p_prefix, 'TRYHARD')), '[^A-Z0-9]+', '', 'g'));
    v_raw text := encode(extensions.gen_random_bytes(12), 'hex');
begin
    if v_prefix = '' then
        v_prefix := 'TRYHARD';
    end if;

    return v_prefix || '-' ||
        upper(substr(v_raw, 1, 4) || '-' ||
              substr(v_raw, 5, 4) || '-' ||
              substr(v_raw, 9, 4) || '-' ||
              substr(v_raw, 13, 4) || '-' ||
              substr(v_raw, 17, 4) || '-' ||
              substr(v_raw, 21, 4));
end;
$$;

