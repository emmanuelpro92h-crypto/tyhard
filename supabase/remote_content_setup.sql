create or replace function public.admin_list_remote_content_files()
returns table (
    id uuid,
    slug text,
    name text,
    description text,
    category text,
    target_bundle text,
    target_path text,
    version integer,
    storage_path text,
    file_name text,
    mime_type text,
    byte_size bigint,
    sha256 text,
    is_active boolean,
    sync_state text,
    deleted_at timestamptz,
    published_at timestamptz,
    created_at timestamptz,
    updated_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
    if not public.is_license_admin() then
        raise exception 'Not authorized';
    end if;

    return query
    select
        f.id,
        f.slug,
        f.name,
        f.description,
        f.category,
        f.target_bundle,
        f.target_path,
        f.version,
        f.storage_path,
        f.file_name,
        f.mime_type,
        f.byte_size,
        f.sha256,
        f.is_active,
        case
            when f.deleted_at is not null then 'delete_pending'
            when f.published_at is null then 'new_pending'
            when f.updated_at > f.published_at then 'change_pending'
            else 'published'
        end as sync_state,
        f.deleted_at,
        f.published_at,
        f.created_at,
        f.updated_at
    from public.remote_content_files f
    where f.deleted_at is null
       or f.updated_at > coalesce(f.published_at, 'epoch'::timestamptz)
    order by f.updated_at desc, f.name asc;
end;
$$;

